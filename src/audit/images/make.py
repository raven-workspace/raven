"""Generates the audit screenshot fixtures and writes index.ts (base64 strings + sizes).

Pure stdlib. Each shape is a flat colour with a 1px contrasting border, so any stretching or cropping is visible.
The mock exam's terminal screenshots are rendered by shots.mjs into a temporary folder, passed here as the one
argument; every PNG in it is embedded, keyed by its file name. index.ts is the only stored copy.
Run: node --experimental-strip-types src/audit/images/shots.mjs (renders the screenshots, then runs this script)
"""
import base64
import os
import struct
import sys
import zlib

SHAPES = {
    # name: (width, height, fill RGB, border RGB)
    "wide": (2400, 300, (30, 41, 59), (56, 189, 248)),  # a terminal strip
    "tall": (500, 1800, (49, 46, 129), (250, 204, 21)),
    "hd": (1920, 1080, (22, 78, 99), (248, 113, 113)),
    "tiny": (64, 40, (127, 29, 29), (255, 255, 255)),
}


def chunk(tag: bytes, data: bytes) -> bytes:
    body = tag + data
    return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)


def png(width: int, height: int, fill, border) -> bytes:
    edge = bytes([0]) + bytes(border) * width
    mid = bytes([0]) + bytes(border) + bytes(fill) * (width - 2) + bytes(border)
    rows = [edge] + [mid] * (height - 2) + [edge]
    ihdr = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(b"".join(rows), 9)) + chunk(b"IEND", b"")


def png_size(data: bytes) -> tuple:
    return struct.unpack(">II", data[16:24])


def main() -> None:
    if len(sys.argv) != 2 or not os.path.isdir(sys.argv[1]):
        # Without the rendered screenshots index.ts would lose them: shots.mjs renders them and calls this.
        sys.exit("usage: make.py <folder of rendered screenshots>; run shots.mjs instead")
    lines = [
        "// Generated by make.py: do not edit. Flat-colour PNGs with a 1px border, as base64.",
        "export const AUDIT_PNGS = {",
    ]
    for name, (w, h, fill, border) in SHAPES.items():
        b64 = base64.b64encode(png(w, h, fill, border)).decode("ascii")
        lines.append(f'  {name}: {{ width: {w}, height: {h}, base64: "{b64}" }},')
    shots = sys.argv[1]
    for file in sorted(os.listdir(shots)):
        if not file.endswith(".png"):
            continue
        with open(os.path.join(shots, file), "rb") as f:
            data = f.read()
        w, h = png_size(data)
        lines.append(f'  "{file[:-4]}": {{ width: {w}, height: {h}, base64: "{base64.b64encode(data).decode("ascii")}" }},')
    lines.append("} as const;")
    lines.append("")
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "index.ts")
    with open(out, "w") as f:
        f.write("\n".join(lines))


main()
